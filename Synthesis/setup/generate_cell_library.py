"""Generate the functional standard-cell catalog and its Liberty views."""

import argparse
import difflib
import json
from pathlib import Path


SETUP = Path(__file__).resolve().parent
ACTIVE_SUPPLY_VOLTAGES = (1.0, 5.0)
ACTIVE_TEMPERATURES = (-40, 125)


def catalog():
    """Define cells by interface, Boolean outputs, and optional state."""
    cells = {}

    def cell(name, inputs, outputs, *, state=None, clock=None, **attributes):
        if name in cells:
            raise ValueError(f"Duplicate cell {name}")
        cells[name] = {
            "inputs": inputs.split(),
            "outputs": outputs,
            "state": state,
            "clock": clock,
            "attributes": attributes,
        }

    for name, function in {"BUF": "A", "INV": "!A", "CLKBUF": "A", "CLKINV": "!A"}.items():
        cell(name + "_X1", "A", {"Y": function})

    for name, operator in (("AND", "&"), ("OR", "|"), ("XOR", "^")):
        complement = {"AND": "NAND", "OR": "NOR", "XOR": "XNOR"}[name]
        for size in (2, 3, 4):
            inputs = list("ABCD"[:size])
            function = f" {operator} ".join(inputs)
            cell(f"{name}{size}_X1", " ".join(inputs), {"Y": function})
            cell(f"{complement}{size}_X1", " ".join(inputs), {"Y": f"!({function})"})

    for prefix, inner, outer in (("AO", "&", "|"), ("OA", "|", "&")):
        for shape in ((2, 1), (2, 2), (3, 1), (3, 2), (2, 1, 1), (2, 2, 1), (2, 2, 2)):
            groups = [[f"{group}{index}" for index in range(1, count + 1)]
                      if count > 1 else [group] for group, count in zip("ABC", shape)]
            terms = [f"({f' {inner} '.join(group)})" if len(group) > 1 else group[0]
                     for group in groups]
            function = f" {outer} ".join(terms)
            inputs = " ".join(pin for group in groups for pin in group)
            suffix = "".join(map(str, shape)) + "_X1"
            cell(prefix + suffix, inputs, {"Y": function})
            cell(prefix + "I" + suffix, inputs, {"Y": f"!({function})"})

    cell("MUX2_X1", "A B S", {"Y": "(A & !S) | (B & S)"})
    cell("MUX4_X1", "A B C D S0 S1", {
        "Y": "(A & !S0 & !S1) | (B & S0 & !S1) | (C & !S0 & S1) | (D & S0 & S1)",
    })
    cell("HA_X1", "A B", {"SUM": "A ^ B", "COUT": "A & B"})
    cell("FA_X1", "A B CIN", {
        "SUM": "A ^ B ^ CIN", "COUT": "(A & B) | (A & CIN) | (B & CIN)",
    })
    cell("TIELO_X1", "", {"Y": "0"})
    cell("TIEHI_X1", "", {"Y": "1"})

    # Priority when both async controls are asserted is clear, then preset.
    def register(name, edge, *, scan=False, enable=False, clear=False, preset=False):
        inputs = ["D", "CLK"]
        next_state = "D"
        if scan:
            inputs += ["SI", "SE"]
            next_state = "(D & !SE) | (SI & SE)"
        if enable:
            inputs += ["E"]
            next_state = "(D & E) | (IQ & !E)"
        attributes = {"clocked_on": "CLK" if edge == "rise" else "!CLK",
                      "next_state": next_state}
        if clear:
            inputs += ["RN"]
            attributes["clear"] = "!RN"
        if preset:
            inputs += ["SN"]
            attributes["preset"] = "!SN"
        if clear and preset:
            attributes["clear_preset_var1"] = "L"
            attributes["clear_preset_var2"] = "H"
        cell(name + "_X1", " ".join(inputs), {"Q": "IQ"}, state="ff", clock="CLK",
             **attributes)

    for prefix, edge in (("DFF", "rise"), ("DFFN", "fall")):
        register(prefix, edge)
        register(prefix + "R", edge, clear=True)
        register(prefix + "S", edge, preset=True)
        register(prefix + "RS", edge, clear=True, preset=True)
        register(prefix + "E", edge, enable=True)
    register("SDFF", "rise", scan=True)
    register("SDFFR", "rise", scan=True, clear=True)
    register("SDFFS", "rise", scan=True, preset=True)
    register("SDFFRS", "rise", scan=True, clear=True, preset=True)

    for name, enable in (("LATCH", "G"), ("LATCHN", "!G")):
        cell(name + "_X1", "D G", {"Q": "IQ"}, state="latch", enable=enable, data_in="D")
        cell(name + "R_X1", "D G RN", {"Q": "IQ"}, state="latch",
             enable=enable, data_in="D", clear="!RN")
        cell(name + "S_X1", "D G SN", {"Q": "IQ"}, state="latch",
             enable=enable, data_in="D", preset="!SN")
    cell("ICG_X1", "CLK E", {"GCLK": "CLK & IQ"}, state="latch",
         clock="CLK", enable="!CLK", data_in="E")
    cell("ICGT_X1", "CLK E TE", {"GCLK": "CLK & IQ"}, state="latch",
         clock="CLK", enable="!CLK", data_in="E | TE")
    return cells


def temperature_label(temperature):
    return f"n{abs(temperature)}c" if temperature < 0 else f"p{temperature}c"


def render_liberty(cells, corner_id, voltage, temperature):
    lines = [
        "/* Generated by generate_cell_library.py. Functional data only. */",
        f"library (stdcells_{corner_id}) {{",
        f"  nom_voltage : {voltage};",
        f"  nom_temperature : {temperature};",
        f"  voltage_map (VDD, {voltage});",
        "  voltage_map (VSS, 0.0);",
    ]
    for name, model in sorted(cells.items()):
        lines += [
            "",
            f"  cell ({name}) {{",
            "    pg_pin (VDD) { voltage_name : VDD; pg_type : primary_power; }",
            "    pg_pin (VSS) { voltage_name : VSS; pg_type : primary_ground; }",
        ]
        if model["state"]:
            lines.append(f"    {model['state']} (IQ, IQN) {{")
            for key, value in model["attributes"].items():
                rendered = value if key.startswith("clear_preset_var") else json.dumps(value)
                lines.append(f"      {key} : {rendered};")
            lines.append("    }")
        for pin, direction, function in (
            [(pin, "input", None) for pin in model["inputs"]]
            + [(pin, "output", fn) for pin, fn in model["outputs"].items()]
        ):
            lines += [
                f"    pin ({pin}) {{",
                f"      direction : {direction};",
                "      related_power_pin : VDD;",
                "      related_ground_pin : VSS;",
            ]
            if pin == model["clock"]:
                lines.append("      clock : true;")
            if function is not None:
                lines.append(f"      function : {json.dumps(function)};")
            lines.append("    }")
        lines.append("  }")
    return "\n".join([*lines, "}", ""])


def json_text(value):
    return json.dumps(value, indent=2) + "\n"


def generated_files():
    cells = catalog()
    interfaces = {
        "schema_version": 1,
        "library_kind": "functional_only",
        "cells": {
            name: {
                "ports": [
                    {"name": pin, "direction": direction, "width": 1}
                    for direction, pins in (("input", model["inputs"]), ("output", model["outputs"]))
                    for pin in pins
                ],
                "power_pins": ["VDD", "VSS"],
            }
            for name, model in sorted(cells.items())
        },
    }
    corners = {
        "schema_version": 1,
        "library_kind": "functional_only",
        "default_power_state": "on",
        "reference_ground_v": 0.0,
        "cell_interfaces": "cell_interfaces.json",
        "corners": {},
    }
    result = {"cell_interfaces.json": json_text(interfaces)}
    for temperature in ACTIVE_TEMPERATURES:
        for supply in ACTIVE_SUPPLY_VOLTAGES:
            voltage_label = f"{supply:.2f}".replace(".", "v")
            corner_id = f"{voltage_label}_{temperature_label(temperature)}"
            path = f"liberty/stdcells_{corner_id}.lib"
            result[path] = render_liberty(cells, corner_id, supply, temperature)
            corners["corners"][corner_id] = {
                "supply_voltage_v": supply,
                "temperature_c": temperature,
                "power_state": "on",
                "liberty": path,
                "functional_mapping_allowed": True,
                "timing_characterized": False,
            }
    result["corners.json"] = json_text(corners)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in generated files.")
    options = parser.parse_args()
    failed = False
    for name, content in generated_files().items():
        path = SETUP / name
        if options.check:
            actual = path.read_text(encoding="utf-8") if path.exists() else ""
            if actual != content:
                failed = True
                print("".join(difflib.unified_diff(actual.splitlines(True), content.splitlines(True),
                                                 fromfile=name, tofile=f"{name} (generated)")),
                      end="")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    return int(failed)


if __name__ == "__main__":
    raise SystemExit(main())
